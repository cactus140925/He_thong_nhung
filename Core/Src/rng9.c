static void six_digit_parity(uint32_t q, uint8_t *e)
{
    uint32_t hi = q / 1000U;
    uint32_t lo = q - hi * 1000U;
    uint8_t a = parity3[hi], b = parity3[lo];
    e[0] = (uint8_t)((a >> 2U) & 1U);
    e[1] = (uint8_t)((a >> 1U) & 1U);
    e[2] = (uint8_t)(a & 1U);
    e[3] = (uint8_t)((b >> 2U) & 1U);
    e[4] = (uint8_t)((b >> 1U) & 1U);
    e[5] = (uint8_t)(b & 1U);
}

uint16_t RNG9_Next(RNG9_State *state, uint16_t adc)
{
    uint8_t e[12] = {0};
    uint8_t sign;
    double y, ay, t, rem;
    uint32_t q0, q1;
    state->phase += (double)(adc & 0x0FFFu) * RNG9_SCALE;
    if (state->phase >= RNG9_TWO_PI) state->phase -= RNG9_TWO_PI;
    y = sin(state->phase);
    sign = (uint8_t)(y >= 0.0 ? 1u : 0u);
    ay = y >= 0.0 ? y : -y;
    if (ay < 1.0) {
        t = ay * 1000000.0;
        q0 = (uint32_t)t;
        rem = t - (double)q0;
        q1 = (uint32_t)(rem * 1000000.0);
        if (q0 > 999999u) q0 = 999999u;
        if (q1 > 999999u) q1 = 999999u;
        six_digit_parity(q0, &e[0]);
        six_digit_parity(q1, &e[6]);
    }
    return (uint16_t)(
          ((uint16_t)(sign ^ e[0] ^ e[3]) << 0u)
        | ((uint16_t)(e[1] ^ e[4]) << 1u)
        | ((uint16_t)(e[2] ^ e[5]) << 2u)
        | ((uint16_t)(sign ^ e[6] ^ e[9]) << 3u)
        | ((uint16_t)(e[7] ^ e[10]) << 4u)
        | ((uint16_t)(e[8] ^ e[11]) << 5u)
        | ((uint16_t)(sign ^ e[0] ^ e[7]) << 6u)
        | ((uint16_t)(e[1] ^ e[8]) << 7u)
        | ((uint16_t)(e[2] ^ e[9]) << 8u));
}
