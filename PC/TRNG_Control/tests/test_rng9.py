"""RNG9 independent-module, mode isolation, CRC and file-integrity tests."""
import json
from pathlib import Path
import struct
import tempfile
import unittest
import zlib

from trng.controller import Controller
from trng.protocol import Config, WireFramer, encode_binary_block, parse_line, RNG_PACKED_SAMPLES
from trng.rng9 import Sine9, MAX_RATE_HZ, pack_words
from trng.storage import SessionStore
from trng.transport import SimulatedDevice


class RNG9Tests(unittest.TestCase):
    def setUp(self):
        self.events = []
        self.tx = []
        self.controller = Controller(self.tx.append, lambda k, v: self.events.append((k, v)))
        self.framer = WireFramer()

    def start(self, samples=512, rate=1000, supported=True):
        self.controller.rng9_supported = supported
        self.controller.configure(Config(rate, samples, 32, "rng9"), start=True)
        self.controller.accept("config_ok", None)
        self.controller.accept("start_ok", None)

    def feed(self, payload, chunk=1):
        for i in range(0, len(payload), chunk):
            for kind, value in self.framer.feed(payload[i:i + chunk]):
                self.controller.accept(*(parse_line(value) if kind == "line" else (kind, value)))

    def complete(self, words, chunk=1, mode="rng9"):
        count = len(words)
        header = f"{'BEGINR' if mode == 'rng9' else 'BEGINB'},8,{count},1000000\n".encode()
        blocks = b"".join(encode_binary_block(8, i, words[i:i+(RNG_PACKED_SAMPLES if mode == "rng9" else 21)], mode=mode)
                          for i in range(0, count, RNG_PACKED_SAMPLES if mode == "rng9" else 21))
        crc = zlib.crc32(struct.pack(f"<{count}H", *words))
        self.feed(header + blocks + f"END,8,{count},{crc:08X}\n".encode(), chunk)
        return [val for kind, val in self.events if kind == "capture_complete"]

    def test_matches_original_do_an_htn_sine9_reference(self):
        # Constants generated by compiling the original do_an_htn SINE9 engine.
        reference = [73,447,48,40,123,383,428,249,404,154,421,387,224,431,2,278,
                     370,337,60,0,249,13,385,24,199,456,80,232,495,254,179,181]
        engine = Sine9()
        values = [engine.next((i * 29) & 4095) for i in range(512)]
        self.assertEqual(values[:32], reference)
        self.assertEqual(zlib.crc32(struct.pack("<512H", *values)), 0x61c46886)

    def test_pack_bits_and_tail_zero_padding(self):
        self.assertEqual(pack_words([1]), b"\x80\x00")
        self.assertEqual(pack_words([256]), b"\x00\x80")
        self.assertEqual(pack_words([0]), b"\x00\x00")
        self.assertEqual(pack_words([511]), b"\xff\x80")
        self.assertEqual(len(pack_words([123] * 512)), 576)
        self.assertEqual(len(pack_words([123] * 500)), 563)
        with self.assertRaises(ValueError): pack_words([512])
        with self.assertRaises(ValueError): pack_words([-1])

    def test_rng_config_atomic_support_and_max_rate(self):
        self.assertEqual(Config(1000, 512).wire(), b"CMD=CONFIG\nADC_RATE=1000\nSAMPLE=512\nSIZE=32\n")
        self.assertIn(b"MODE=RNG9\nSIZE=32\n", Config(1000, 512, 32, "rng9").wire())
        self.assertEqual(MAX_RATE_HZ, 100000)
        Config(10000, 512, 32, "rng9").validate()
        with self.assertRaises(ValueError): Config(100001, 512, 32, "rng9").validate()
        with self.assertRaises(ValueError): Config(1000, 512, 32, "x").validate()
        with self.assertRaises(ValueError): self.start(supported=False)
        self.assertEqual(self.tx, [])
        self.controller.accept("info", "ADC_BIN_2_7;HZ=100000;MAX=1000000;LINK=USB;RNG9=1")
        self.assertTrue(self.controller.rng9_supported)
        self.controller.accept("info", "ADC_BIN_2_7;HZ=100000;MAX=1000000;LINK=USB")
        self.assertFalse(self.controller.rng9_supported)

    def test_crc_valid_chunk_fragmentation_and_binary_file(self):
        for chunk in (1, 7, 62, 512, 4096):
            with self.subTest(chunk=chunk):
                self.setUp(); self.start()
                engine = Sine9()
                words = [engine.next((i * 29) & 4095) for i in range(512)]
                result, = self.complete(words, chunk)
                self.assertEqual(result["mode"], "rng9")
                self.assertEqual(result["samples"], words)
                self.assertEqual(self.controller.state, "idle")
                with tempfile.TemporaryDirectory() as directory:
                    store = SessionStore(directory, "MODELED_STM32", 115200)
                    try:
                        path = store.rng_capture(result)
                        self.assertEqual(path.read_bytes(), pack_words(words))
                        self.assertEqual(path.stat().st_size, 576)
                        meta = json.loads(path.with_suffix(".json").read_text())
                        self.assertEqual(meta["output_bits"], 4608)
                        self.assertEqual(meta["padding_bits_at_end"], 0)
                        self.assertFalse(meta["entropy_validated"])
                        exported = Path(directory) / "copy.bin"
                        store.export("rng9", exported)
                        self.assertEqual(exported.read_bytes(), path.read_bytes())
                    finally:
                        store.close()

    def test_rng_progress_is_delivered_only_to_rng_tab(self):
        # Regression: v2.8 mistakenly re-labelled RNG blocks as raw ADC blocks.
        self.start()
        self.feed(b"BEGINR,8,512,1000000\n")
        self.feed(encode_binary_block(8, 0, [7, 13, 511], mode="rng9"))
        self.assertEqual([k for k, _ in self.events if k == "capture_block_rng"],
                         ["capture_block_rng"])
        self.assertNotIn("capture_block", [k for k, _ in self.events])
        self.assertEqual(self.controller.capture.samples, [7, 13, 511])

    def test_storage_revalidates_word_crc_even_with_complete_status(self):
        words = [1, 256]
        forged = {"mode": "rng9", "wire_format": "rng9", "status": "complete",
                  "samples": words, "requested_samples": 2, "crc32": "00000000",
                  "run_id": 1, "device_session": 8, "adc_rate_hz": 1000,
                  "pc_elapsed_ms": 0.5}
        with tempfile.TemporaryDirectory() as directory:
            store = SessionStore(directory, "TEST", 115200)
            try:
                with self.assertRaisesRegex(ValueError, "CRC32"):
                    store.rng_capture(forged)
                self.assertFalse(list(store.path.glob("*.bin")))
                self.assertIsNone(store.last_rng_path)
                # A correct CRC and valid mode allow the exact same samples.
                forged["crc32"] = f"{zlib.crc32(struct.pack('<2H', *words)):08X}"
                saved = store.rng_capture(forged)
                self.assertEqual(saved.read_bytes(), pack_words(words))
                forged["wire_format"] = "binary"
                with self.assertRaises(ValueError):
                    store.rng_capture(forged)
            finally:
                store.close()

    def test_wrong_begin_mode_never_produces_output(self):
        self.start()
        self.complete([42] * 512, mode="raw")
        self.assertEqual(self.controller.state, "uncertain")
        self.assertFalse([x for kind, x in self.events if kind == "capture_complete"])
        self.assertTrue([x for kind, x in self.events if kind == "warning"])

    def test_rng_kind_mismatch_and_corrupt_crc_rejected(self):
        self.start()
        self.feed(b"BEGINR,8,512,1000000\n")
        self.feed(encode_binary_block(8, 0, [0] * 21, mode="raw"))
        self.assertEqual(self.controller.state, "uncertain")
        self.assertFalse([x for kind, x in self.events if kind == "capture_complete"])
        self.setUp(); self.start()
        self.feed(b"BEGINR,8,512,1000000\n")
        frame = bytearray(encode_binary_block(8, 0, [44] * 21, mode="rng9"))
        frame[22] ^= 0x20
        self.feed(frame)
        self.assertEqual(self.controller.state, "uncertain")
        self.assertFalse([x for kind, x in self.events if kind == "capture_complete"])

    def test_rng_word_over_511_rejected_even_if_crc_valid(self):
        self.start()
        self.feed(b"BEGINR,8,512,1000000\n")
        # Type 2 legacy RNG9 still contains 16-bit slots that can
        # encode invalid values. Packed type3 intrinsically cannot exceed 511.
        frame = bytearray(encode_binary_block(8, 0, [511] * 21, mode="rng9", legacy_rng9=True))
        struct.pack_into("<H", frame, 16, 512)
        struct.pack_into("<I", frame, 58, zlib.crc32(frame[4:58]))
        self.feed(frame)
        self.assertEqual(self.controller.state, "uncertain")

    def test_incomplete_rng_cannot_be_saved(self):
        with tempfile.TemporaryDirectory() as directory:
            store = SessionStore(directory, "MODELED_STM32", 115200)
            try:
                with self.assertRaises(ValueError):
                    store.rng_capture({"mode":"rng9", "status":"complete", "samples":[0],
                                       "requested_samples":512})
                self.assertFalse(list(store.path.glob("*.bin")))
                self.assertIsNone(store.last_rng_path)
            finally:
                store.close()

    def test_simulation_rng_stream_and_switch_back_to_adc(self):
        device = SimulatedDevice()
        config = Config(1000, 250, 32, "rng9")
        self.assertEqual(device.write(config.wire()), len(config.wire()))
        self.assertEqual(device.config.mode, "rng9")
        device.write(b"START\n")
        # Force simulated elapsed time to exceed one complete run.
        device.started -= 2
        data = b"".join(device.read(4096) for _ in range(10))
        self.assertIn(b"BEGINR,", data)
        self.assertIn(b"\xA5\x5A\xC3\x3C\x01\x03", data)
        self.assertIn(b"END,", data)
        device.write(Config(1000, 250, 32).wire())
        self.assertEqual(device.config.mode, "raw")


if __name__ == "__main__":
    unittest.main()
